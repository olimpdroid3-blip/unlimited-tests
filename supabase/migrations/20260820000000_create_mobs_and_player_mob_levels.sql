CREATE TABLE public.mobs (
  id text NOT NULL PRIMARY KEY,
  name text NOT NULL CHECK (btrim(name) <> ''),
  image_url text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.player_mob_levels (
  player_id uuid NOT NULL REFERENCES public.battle_power(id) ON DELETE CASCADE,
  mob_id text NOT NULL REFERENCES public.mobs(id) ON DELETE CASCADE,
  level smallint NOT NULL CHECK (level BETWEEN 1 AND 30),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (player_id, mob_id)
);

CREATE INDEX player_mob_levels_mob_id_idx
  ON public.player_mob_levels (mob_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.mobs TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.player_mob_levels TO anon, authenticated;
GRANT ALL ON public.mobs TO service_role;
GRANT ALL ON public.player_mob_levels TO service_role;

ALTER TABLE public.mobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.player_mob_levels ENABLE ROW LEVEL SECURITY;

CREATE POLICY mobs_all_anon
  ON public.mobs
  FOR ALL TO anon, authenticated
  USING (true)
  WITH CHECK (true);

CREATE POLICY player_mob_levels_all_anon
  ON public.player_mob_levels
  FOR ALL TO anon, authenticated
  USING (true)
  WITH CHECK (true);

CREATE TRIGGER mobs_touch_updated_at
  BEFORE UPDATE ON public.mobs
  FOR EACH ROW EXECUTE FUNCTION public.tower_touch_updated_at();

CREATE TRIGGER player_mob_levels_touch_updated_at
  BEFORE UPDATE ON public.player_mob_levels
  FOR EACH ROW EXECUTE FUNCTION public.tower_touch_updated_at();

