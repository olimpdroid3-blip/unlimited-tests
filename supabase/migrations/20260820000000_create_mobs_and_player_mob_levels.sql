INSERT INTO public.player_mob_levels (player_id, mob_id, level)
SELECT
  player.id,
  level_seed.mob_id,
  level_seed.level
FROM mob_level_seed AS level_seed
JOIN mob_player_seed AS player_seed
  ON player_seed.local_id = level_seed.local_player_id
JOIN LATERAL (
  SELECT battle_power.id
  FROM public.battle_power
  WHERE lower(btrim(battle_power.nickname)) = lower(btrim(player_seed.nickname))
  ORDER BY battle_power.created_at, battle_power.id
  LIMIT 1
) AS player ON true
WHERE true
ON CONFLICT (player_id, mob_id) DO UPDATE SET
  level = EXCLUDED.level,
  updated_at = now();

DO $$
DECLARE
  seeded_player_count integer;
  seeded_level_count integer;
BEGIN
  SELECT count(*)
  INTO seeded_player_count
  FROM mob_player_seed AS player_seed
  WHERE EXISTS (
    SELECT 1
    FROM public.battle_power AS player
    WHERE lower(btrim(player.nickname)) = lower(btrim(player_seed.nickname))
  );

  SELECT count(*)
  INTO seeded_level_count
  FROM mob_level_seed AS level_seed
  JOIN mob_player_seed AS player_seed
    ON player_seed.local_id = level_seed.local_player_id
  JOIN LATERAL (
    SELECT battle_power.id
    FROM public.battle_power
    WHERE lower(btrim(battle_power.nickname)) = lower(btrim(player_seed.nickname))
    ORDER BY battle_power.created_at, battle_power.id
    LIMIT 1
  ) AS player ON true
  JOIN public.player_mob_levels AS stored_level
    ON stored_level.player_id = player.id
    AND stored_level.mob_id = level_seed.mob_id
    AND stored_level.level = level_seed.level;

  IF seeded_player_count <> 17 THEN
    RAISE EXCEPTION 'Expected 17 seeded players, found %', seeded_player_count;
  END IF;

  IF seeded_level_count <> 606 THEN
    RAISE EXCEPTION 'Expected 606 seeded mob levels, found %', seeded_level_count;
  END IF;
END;
$$;
